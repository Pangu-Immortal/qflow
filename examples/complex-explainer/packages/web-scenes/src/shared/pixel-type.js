export function pixelType(text) {
  let x = 0;
  const letters = [...text]
    .map((letter, index) => {
      const rows = glyphs[letter];
      if (!rows) throw Error("Missing closing-card glyph: " + letter);
      const rects = rows
        .flatMap((row, y) =>
          [...row].flatMap((bit, i) =>
            bit === "1" ? `<rect x="${x + i}" y="${y}" width="1" height="1"/>` : [],
          ),
        )
        .join("");
      x += rows[0].length + 1;
      return `<g class="pixel-letter" data-letter="${index}">${rects}</g>`;
    })
    .join("");
  return `<svg viewBox="0 0 ${x - 1} 7" role="img" aria-label="${text}" shape-rendering="crispEdges" fill="currentColor">${letters}</svg>`;
}
